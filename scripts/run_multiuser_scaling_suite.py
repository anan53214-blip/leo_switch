def has_training_artifacts(run_dir: Path) -> bool:
    return any((run_dir / filename).exists() for filename in TRAIN_ARTIFACTS)


def format_command(command: Sequence[str]) -> str:
    return " ".join(shlex.quote(part) for part in command)


def run_command(command: Sequence[str], cwd: Path, log_path: Path, dry_run: bool) -> None:
    command_text = format_command(command)
    print(command_text, flush=True)
    if dry_run:
        return

    log_path.parent.mkdir(parents=True, exist_ok=True)
    env = dict(os.environ)
    env["PYTHONUNBUFFERED"] = "1"
    with log_path.open("a", encoding="utf-8") as log_file:
        log_file.write(f"\n$ {command_text}\n")
        log_file.flush()
        process = subprocess.Popen(
            list(command),
            cwd=cwd,
            env=env,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            text=True,
            encoding="utf-8",
            errors="replace",
        )
        assert process.stdout is not None
        for line in process.stdout:
            print(line, end="")
            log_file.write(line)
        return_code = process.wait()
        if return_code != 0:
            raise subprocess.CalledProcessError(return_code, command)


def method_display_name(method: str, fallback: str = "") -> str:
    if method in METHOD_DISPLAY_NAMES:
        return METHOD_DISPLAY_NAMES[method]
    if fallback and fallback in METHOD_DISPLAY_NAMES.values():
        return fallback
    return fallback or method


def _read_comparison_rows(summary_csv: Path, num_users: int) -> list[dict[str, str]]:
    rows: list[dict[str, str]] = []
    with summary_csv.open("r", encoding="utf-8", newline="") as handle:
        reader = csv.DictReader(handle)
        for row in reader:
            method = row.get("method", "")
            normalized = dict(row)
            normalized["num_users"] = str(num_users)
            normalized["display_name"] = method_display_name(method, row.get("display_name", ""))
            rows.append(normalized)
    return rows


def aggregate_user_summaries(
    suite_dir: Path,
    user_counts: Sequence[int],
) -> tuple[list[dict[str, str]], Path]:
    rows: list[dict[str, str]] = []
    for num_users in user_counts:
        summary_csv = suite_dir / f"u{num_users}" / "comparison_summary.csv"
        if not summary_csv.exists():
            raise FileNotFoundError(f"Missing comparison summary: {summary_csv}")
        rows.extend(_read_comparison_rows(summary_csv, num_users))

    fieldnames: list[str] = ["num_users", "method", "display_name"]
    for row in rows:
        for key in row:
            if key not in fieldnames:
                fieldnames.append(key)

    output_csv = suite_dir / "multiuser_summary.csv"
    output_csv.parent.mkdir(parents=True, exist_ok=True)
    with output_csv.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)
    return rows, output_csv


def _float_or_none(value: object) -> Optional[float]:
    try:
        if value is None or value == "":
            return None
        return float(value)
    except (TypeError, ValueError):
        return None


def _method_order(rows: Sequence[dict[str, str]]) -> list[str]:
    preferred = list(METHOD_DISPLAY_NAMES.values())
    present = {row.get("display_name", "") for row in rows}
    ordered = [name for name in preferred if name in present]
    ordered.extend(sorted(name for name in present if name and name not in ordered))
    return ordered


def setup_plot_style() -> None:
    plt.rcParams.update(
        {
            "font.family": "serif",
            "font.serif": ["Times New Roman", "DejaVu Serif"],
            "font.size": 11,
            "axes.titlesize": 12,
            "axes.labelsize": 11,
            "legend.fontsize": 9,
            "lines.linewidth": 1.8,
            "lines.markersize": 5,
            "figure.dpi": 220,
            "savefig.dpi": 300,
            "savefig.bbox": "tight",
            "axes.grid": True,
            "grid.alpha": 0.45,
            "grid.linestyle": "--",
        }
    )


def plot_scaling_metrics(
    rows: Sequence[dict[str, str]],
    suite_dir: Path,
    metric_specs: Sequence[tuple[str, str, str, float]],
    filename: str,
) -> Optional[Path]:
    if not rows:
        return None
    setup_plot_style()
    cols = 2
    metric_count = len(metric_specs)
    rows_count = (metric_count + cols - 1) // cols
    fig, axes = plt.subplots(rows_count, cols, figsize=(11, 4.2 * rows_count), squeeze=False)
    method_names = _method_order(rows)
    markers = ["o", "s", "^", "D", "v", "P", "X", "*", "h"]

    for ax, (metric_key, title, ylabel, scale) in zip(axes.flat, metric_specs):
        for index, display_name in enumerate(method_names):
            method_rows = [
                row for row in rows
                if row.get("display_name") == display_name and _float_or_none(row.get(metric_key)) is not None
            ]
            method_rows.sort(key=lambda row: int(row["num_users"]))
            if not method_rows:
                continue
            x_values = [int(row["num_users"]) for row in method_rows]
            y_values = [float(row[metric_key]) * scale for row in method_rows]
            ax.plot(
                x_values,
                y_values,
                marker=markers[index % len(markers)],
                label=display_name,
            )
        ax.set_title(title)
        ax.set_xlabel("Number of Users")
        ax.set_ylabel(ylabel)
        ax.set_xticks(sorted({int(row["num_users"]) for row in rows}))

    for ax in axes.flat[metric_count:]:
        ax.axis("off")

    handles, labels = axes.flat[0].get_legend_handles_labels()
    if handles:
        fig.legend(handles, labels, loc="upper center", ncol=min(5, len(labels)), frameon=True)
        fig.subplots_adjust(top=0.88)
    output_path = suite_dir / filename
    fig.savefig(output_path)
    plt.close(fig)
    return output_path


def _load_training_curve(history_path: Path) -> tuple[list[float], list[float]]:
    if not history_path.exists():
        return [], []
    with history_path.open("r", encoding="utf-8") as handle:
        payload = json.load(handle)
    steps: list[float] = []
    rewards: list[float] = []
    for record in payload.get("training", []):
        reward = _float_or_none(record.get("mean_reward", record.get("reward")))
        step = _float_or_none(record.get("total_steps", record.get("step")))
        if reward is None or step is None:
            continue
        steps.append(step)
        rewards.append(reward)
    return steps, rewards


def training_history_path(paths: SuitePaths, method: str) -> Path:
    if method == "han_mappo":
        return paths.system_run_dir / "training_history.json"
    return paths.compare_output_dir / "learned_baselines" / method / "training_history.json"


def plot_reward_convergence(
    project_root: Path,
    run_id: str,
    user_counts: Sequence[int],
    suite_dir: Path,
) -> Optional[Path]:
    setup_plot_style()
    fig, axes = plt.subplots(1, len(user_counts), figsize=(5.2 * len(user_counts), 4.2), squeeze=False)
    plotted_any = False
    markers = ["o", "s", "^", "D", "v"]

    for axis_index, num_users in enumerate(user_counts):
        ax = axes.flat[axis_index]
        paths = build_paths(project_root, run_id, num_users)
        for method_index, method in enumerate(LEARNED_REWARD_METHODS):
            history_path = training_history_path(paths, method)
            steps, rewards = _load_training_curve(history_path)
            if not steps:
                continue
            plotted_any = True
            ax.plot(
                steps,
                rewards,
                marker=markers[method_index % len(markers)],
                markevery=max(len(steps) // 8, 1),
                label=method_display_name(method),
            )
        ax.set_title(f"U{num_users}")
        ax.set_xlabel("Training Steps")
        ax.set_ylabel("Mean Episode Reward")

    handles, labels = axes.flat[0].get_legend_handles_labels()
    if handles:
        fig.legend(handles, labels, loc="upper center", ncol=min(5, len(labels)), frameon=True)
        fig.subplots_adjust(top=0.82)

    if not plotted_any:
        plt.close(fig)
        return None
    output_path = suite_dir / "multiuser_reward_convergence.png"
    fig.savefig(output_path)
    plt.close(fig)
    return output_path


def write_manifest(
    suite_dir: Path,
    config: MultiUserConfig,
    generated_paths: Iterable[Path],
) -> Path:
    manifest_path = suite_dir / "suite_manifest.json"
    payload = {
        "run_id": config.run_id,
        "generated_at": datetime.now().isoformat(timespec="seconds"),
        "config": asdict(config),
        "method_display_names": METHOD_DISPLAY_NAMES,
        "generated_artifacts": [str(path) for path in generated_paths],
    }
    with manifest_path.open("w", encoding="utf-8") as handle:
        json.dump(payload, handle, ensure_ascii=False, indent=2)
    return manifest_path


def generate_aggregate_artifacts(
    project_root: Path,
    config: MultiUserConfig,
    suite_dir: Path,
) -> list[Path]:
    summary_rows, summary_csv = aggregate_user_summaries(suite_dir, config.user_counts)
    generated: list[Path] = [summary_csv]

    reward_plot = plot_reward_convergence(project_root, config.run_id, config.user_counts, suite_dir)
    if reward_plot is not None:
        generated.append(reward_plot)
    core_plot = plot_scaling_metrics(
        summary_rows,
        suite_dir,
        CORE_SCALING_METRICS,
        "multiuser_core_metrics.png",
    )
    if core_plot is not None:
        generated.append(core_plot)
    resource_plot = plot_scaling_metrics(
        summary_rows,
        suite_dir,
        RESOURCE_SCALING_METRICS,
        "multiuser_resource_metrics.png",
    )
    if resource_plot is not None:
        generated.append(resource_plot)
    manifest = write_manifest(suite_dir, config, generated)
    generated.append(manifest)
    return generated


