@dataclass(frozen=True)
class SuitePaths:
    suite_dir: Path
    system_run_dir: Path
    compare_output_dir: Path
    log_dir: Path


@dataclass(frozen=True)
class MultiUserConfig:
    run_id: str
    user_counts: tuple[int, ...] = DEFAULT_USER_COUNTS
    python_executable: str = DEFAULT_PYTHON
    seed: int = 42
    device: str = "auto"
    total_timesteps: int = 300_000
    max_steps: int = 600
    n_steps: int = 1024
    eval_interval: int = 50_000
    eval_episodes: int = 3
    save_interval: int = 100_000
    graph_update_interval: int = 1
    log_interval: int = 1
    best_model_metric: str = "avg_delay"
    compare_ranking_metric: str = "avg_delay"
    compare_episodes: int = 3
    plot_window: int = 5
    early_stop_patience: int = 0
    baselines: tuple[str, ...] = DEFAULT_BASELINES
    skip_system_train: bool = False
    skip_compare: bool = False
    force_system_train: bool = False
    reuse_learned_checkpoints: bool = False
    aggregate_only: bool = False
    dry_run: bool = False


def resolve_run_id(run_id: Optional[str] = None, now: Optional[datetime] = None) -> str:
    if run_id:
        return run_id
    return (now or datetime.now()).strftime("%Y%m%d_%H%M%S")


def build_paths(project_root: Path, run_id: str, num_users: int) -> SuitePaths:
    results_dir = project_root / "results"
    suite_dir = results_dir / "baseline_compare" / f"multiuser_scaling_{run_id}"
    return SuitePaths(
        suite_dir=suite_dir,
        system_run_dir=results_dir / f"full_train_latency_priority_multiuser_u{num_users}_{run_id}",
        compare_output_dir=suite_dir / f"u{num_users}",
        log_dir=results_dir / "logs",
    )


def _path_arg(path: Path) -> str:
    return str(path)


